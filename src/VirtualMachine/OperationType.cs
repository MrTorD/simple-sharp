namespace VirtualMachine;

public enum OperationType
{
    /// <summary>
    /// Остановка выполнения программы
    /// </summary>
    Halt,

    /// <summary>
    /// Добавление значение на вершину стека
    /// </summary>
    Push,

    /// <summary>
    /// Снимает значение с вершины стека
    /// </summary>
    Pop,

    /// <summary>
    /// Снимает два значения с вершины стека, помещает их сумму на вершину стека
    /// </summary>
    Add,

    /// <summary>
    /// Снимает два значения с вершины стека, помещает на вершину стека результат вычитания второго снятого значения на первое
    /// </summary>
    Sub,

    /// <summary>
    /// Снимает два значения с вершины стека, помещает их произведение на вершину стека
    /// </summary>
    Mul,

    /// <summary>
    /// Снимает два значения с вершины стека, помещает на вершину стека результат деления нацело второго снятого значения на первое
    /// </summary>
    Div,

    /// <summary>
    /// Снимает два значения с вершины стека, помещает на вершину стека результат возведения второго снятого значения в степень первого
    /// </summary>
    Exponent,

    /// <summary>
    /// Снимает два значения с вершины стека, помещает на вершину стека остаток от деления второго снятого значения на первое
    /// </summary>
    DivWithRemainder,

    /// <summary>
    /// Снимает значение с вершины стека, помещает на вершину противоположное число
    /// </summary>
    Negate,

    /// <summary>
    /// Снимает последние значение с вершины стека, выводит его в стандартный поток вывода
    /// </summary>
    Write,
}